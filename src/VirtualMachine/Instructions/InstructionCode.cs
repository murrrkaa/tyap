namespace Mlt.VirtualMachine.Instructions;

public enum InstructionCode
{
    /// <summary>
    /// Добавляет значение в стек вычислений.
    /// </summary>
    Push,

    /// <summary>
    /// Удаляет значение с вершины стека вычислений.
    /// </summary>
    Pop,

    /// <summary>
    /// Забирает значение из стека вычислений, записывает его в новую переменную с указанным именем.
    /// </summary>
    DefineVar,

    /// <summary>
    /// Забирает значение из стека вычислений, записывает его в существующую переменную с указанным именем.
    /// </summary>
    StoreVar,

    /// <summary>
    /// Читает значение переменной с указанным именем, записывает его в стек вычислений.
    /// </summary>
    LoadVar,

    /// <summary>
    /// Складывает два числа на стеке вычислений.
    /// </summary>
    Add,

    /// <summary>
    /// Вычитает два числа на стеке вычислений.
    /// </summary>
    Subtract,

    /// <summary>
    /// Умножает два числа на стеке вычислений.
    /// </summary>
    Multiply,

    /// <summary>
    /// Делит два числа на стеке вычислений.
    /// </summary>
    Divide,

    /// <summary>
    /// Применяет логическое НЕ к значению на вершине стека вычислений.
    /// Снимает значение и кладёт результат обратно.
    /// </summary>
    Not,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат проверки равенства.
    /// </summary>
    Equal,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат проверки неравенства.
    /// </summary>
    NotEqual,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат операции "меньше".
    /// </summary>
    Less,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат операции "меньше или равно".
    /// </summary>
    LessOrEqual,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат операции "больше".
    /// </summary>
    GreaterThan,

    /// <summary>
    /// Забирает два значения со стека вычислений и добавляет в стек булев результат операции "больше или равно".
    /// </summary>
    GreaterThanOrEqual,

    /// <summary>
    /// Безусловный переход, меняет указатель инструкций.
    /// Нумерация инструкций начинается с нуля.
    /// </summary>
    Jump,

    /// <summary>
    /// Условный переход: выполняется, если значение на вершине стека — true.
    /// Значение остаётся на стеке (не снимается).
    /// Используется для short-circuit вычисления оператора or.
    /// </summary>
    JumpIfTrue,

    /// <summary>
    /// Условный переход: выполняется, если значение на вершине стека — false.
    /// Значение остаётся на стеке (не снимается).
    /// Используется для short-circuit вычисления оператора and.
    /// </summary>
    JumpIfFalse,

    /// <summary>
    /// Выполняет вызов встроенной функции с указанным кодом.
    /// Забирает аргументы со стека вычислений.
    /// Возвращает результат вызова в стек вычислений.
    /// </summary>
    CallBuiltin,

    /// <summary>
    /// Выполняет вызов функции: переходит на указанную инструкцию,
    /// сохраняя прежнее значение указателя инструкций в стек возвратов.
    /// </summary>
    Call,

    /// <summary>
    /// Выполняет возврат из функции: восстанавливает значение указателя инструкций из стека возвратов.
    /// </summary>
    Return,

    /// <summary>
    /// Останавливает выполнение программы.
    /// Снимает значение со стека вычислений, используя его как целочисленный код возврата.
    /// </summary>
    Halt,

    /// <summary>
    /// Добавляет новую таблицу переменных в стек таблиц переменных.
    /// </summary>
    PushVars,

    /// <summary>
    /// Убирает таблицу переменных со стека таблиц переменных.
    /// </summary>
    PopVars,
}